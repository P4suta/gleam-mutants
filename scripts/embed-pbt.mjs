// Embeds the verbatim text of src/gleam_mutants/pbt.gleam into a generated
// Gleam module so the suggestion runner can write it into user snapshots
// without shipping a separate asset.

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";

const rawChunkSize = 768;

export function pbtSourcePath(root) {
  return path.join(root, "src", "gleam_mutants", "pbt.gleam");
}

export function pbtModulePath(root) {
  return path.join(root, "src", "gleam_mutants", "suggest", "pbt_source.gleam");
}

export function renderPbtModule(root) {
  const source = fs.readFileSync(pbtSourcePath(root));
  const chunks = [];
  for (let offset = 0; offset < source.length; offset += rawChunkSize) {
    chunks.push(source.subarray(offset, offset + rawChunkSize).toString("base64"));
  }
  if (chunks.length === 0) {
    throw new Error("src/gleam_mutants/pbt.gleam is empty");
  }
  return `// SPDX-FileCopyrightText: 2026 gleam_mutants contributors
// SPDX-License-Identifier: MIT OR Apache-2.0

// Generated by scripts/embed-pbt.mjs from src/gleam_mutants/pbt.gleam.
// Do not edit by hand.
import gleam/bit_array
import gleam/list

/// The verbatim text of \`src/gleam_mutants/pbt.gleam\`, ready to be written
/// into a snapshot alongside the generated probe.
pub fn source() -> String {
  let assert Ok(decoded) = list.try_map(chunks(), bit_array.base64_decode)
  let assert Ok(text) = bit_array.to_string(bit_array.concat(decoded))
  text
}

fn chunks() -> List(String) {
  [
${chunks.map(chunk => `    ${JSON.stringify(chunk)},`).join("\n")}
  ]
}
`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const root = process.cwd();
  const destination = pbtModulePath(root);
  fs.writeFileSync(destination, renderPbtModule(root), "utf8");
  console.log(`Embedded ${path.relative(root, pbtSourcePath(root))} into ${path.relative(root, destination)}`);
}
